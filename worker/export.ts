import type { Run } from "../shared/schemas";
import { getProvider } from "./providers";

/** Renders a run as a Markdown report (copy-paste + .md download). */
export function runToMarkdown(run: Run): string {
  const lines: string[] = [];
  lines.push(`# SearchBench — ${run.query}`);
  lines.push(``);
  lines.push(`- Run: \`${run.id}\``);
  lines.push(`- Date: ${run.createdAt}`);
  lines.push(`- Mode: ${run.mode}`);
  lines.push(`- Providers: ${Object.keys(run.providerRuns).join(", ")}`);
  lines.push(``);

  for (const [providerId, pr] of Object.entries(run.providerRuns)) {
    const name = getProvider(providerId)?.name ?? providerId;
    lines.push(`## ${name} (${pr.status}, ${(pr.latencyMs / 1000).toFixed(1)}s)`);
    if (pr.status !== "ok") {
      lines.push(``);
      lines.push(`> ${pr.error ?? "No results."}`);
      lines.push(``);
      continue;
    }
    lines.push(``);
    pr.results.forEach((r, i) => {
      lines.push(`### ${i + 1}. [${r.title}](${r.url})`);
      if (r.publishedDate) lines.push(`*Published: ${r.publishedDate}*`);
      lines.push(``);
      lines.push(r.snippet || "_(no excerpt)_");
      lines.push(``);
    });
  }

  if (run.judge) {
    const j = run.judge;
    lines.push(`## AI judge (${j.model})`);
    lines.push(``);
    lines.push(`Ranking: ${j.ranking.join(" → ")}`);
    lines.push(``);
    lines.push(`| Provider | Score | Verdict |`);
    lines.push(`| --- | ---: | --- |`);
    for (const o of j.overall) {
      lines.push(`| ${o.providerId} | ${o.score} | ${o.verdict} |`);
    }
    lines.push(``);
    lines.push(`| Provider | Relevance | Freshness | Depth | Source quality | Snippet usefulness |`);
    lines.push(`| --- | ---: | ---: | ---: | ---: | ---: |`);
    for (const d of j.dimensions) {
      lines.push(
        `| ${d.providerId} | ${d.relevance} | ${d.freshness} | ${d.depth} | ${d.sourceQuality} | ${d.snippetUsefulness} |`,
      );
    }
    lines.push(``);
    for (const s of j.strengths) {
      lines.push(`**${s.providerId} strengths:**`);
      for (const p of s.points) lines.push(`- ${p}`);
      lines.push(``);
    }
    for (const w of j.weaknesses) {
      lines.push(`**${w.providerId} weaknesses:**`);
      for (const p of w.points) lines.push(`- ${p}`);
      lines.push(``);
    }
    if (j.notes.length > 0) {
      lines.push(`**Cross-provider notes:**`);
      for (const n of j.notes) lines.push(`- ${n}`);
      lines.push(``);
    }
  } else if (run.judgeError) {
    lines.push(`## AI judge`);
    lines.push(``);
    lines.push(`> Judge failed: ${run.judgeError}`);
    lines.push(``);
  }

  lines.push(`---`);
  lines.push(`*Generated by SearchBench.*`);
  lines.push(``);
  return lines.join("\n");
}
